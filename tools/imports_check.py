#!/usr/bin/env python3
"""Cross-checks decompiled/macho/imports.txt against the loader's import tables (source/*.c) and writes
docs/imports.md (symbol -> shim file -> status). Exit code 1 if any import would land in ml_unimpl_entry.

Status: real = implemented (or bound to the VitaSDK library of the same name); stub = deliberately
returns "unavailable"/no-op (marked with a `stub:` comment on the table line or in STUB_FILES);
dynamic = resolved at bind time by objc_import_lookup (_OBJC_CLASS_$_*, NSString constants).

Uso: python3 -I tools/imports_check.py [--md docs/imports.md]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'source')
imports = [l.strip() for l in open(os.path.join(ROOT, 'decompiled/macho/imports.txt')) if l.strip().startswith('_') or l.strip() == 'dyld_stub_binder']

ENTRY = re.compile(r'\b(?:F|D|V|FS|STUB)\(\s*([A-Za-z0-9_$]+)|(?:\{|F_RAW\()\s*"(_?[A-Za-z0-9_$]+)"\s*,')
where = {}  # symbol -> (file, is_stub)
for f in sorted(os.listdir(SRC)):
    if f.startswith('._') or not f.endswith('.c'):
        continue
    for line in open(os.path.join(SRC, f), encoding='utf-8', errors='replace'):
        stub = 'stub' in line.lower() or 'STUB(' in line
        for m in ENTRY.finditer(line):
            n = m.group(1)
            n = '_' + n if n else m.group(2)
            where.setdefault(n, (f, stub))

objc_src = open(os.path.join(SRC, 'objc.c'), encoding='utf-8').read()
consts = set(re.findall(r'"([A-Za-z0-9_]+)"', objc_src[objc_src.index('const_names[] = {'):objc_src.index('#define NCONST')]))

def area(s):
    if s.startswith('_OBJC_') or s.startswith('_objc_') or s.startswith('_NS') or s.startswith('_CF') or s.startswith('_kCF') or s == '___CFConstantStringClassReference': return 'ObjC/Foundation/CF'
    if s.startswith('_gl'): return 'OpenGL ES'
    if s.startswith('_al') or s.startswith('_Audio'): return 'Audio'
    if s.startswith('_UI') or s.startswith('_CG') or s.startswith('_CA') or s.startswith('_kCA') or s.startswith('_kEAGL') or s.startswith('_MP'): return 'UIKit/CG/MediaPlayer'
    if s.startswith('__Z') or s.startswith('___cxa') or s.startswith('___gxx') or s == '___dynamic_cast': return 'C++ runtime'
    if s.startswith('_SC') or s.startswith('_kSC') or s.startswith('_CFNetwork') or s.startswith('_AB') or s.startswith('_kAB') or s.startswith('_GK') or s.startswith('_CL') or s.startswith('_CC_'): return 'Network/GameKit/AddressBook/Crypto'
    if s in ('_compress2', '_uncompress', '_crc32', '_inflate', '_deflate') or s.startswith('_inflate') or s.startswith('_deflate'): return 'zlib'
    return 'libc/math/pthread'

rows, missing = [], []
for s in imports:
    if s in where:
        f, stub = where[s]
        rows.append((area(s), s, f, 'stub' if stub else 'real'))
    elif s.startswith('_OBJC_CLASS_$_') or s.startswith('_OBJC_METACLASS_$_') or s == '___CFConstantStringClassReference':
        rows.append((area(s), s, 'objc.c (objc_import_lookup)', 'dynamic'))
    elif s[1:] in consts:
        rows.append((area(s), s, 'objc.c (const_names)', 'real'))
    else:
        rows.append((area(s), s, '-', 'MISSING'))
        missing.append(s)

out = None
if '--md' in sys.argv:
    out = sys.argv[sys.argv.index('--md') + 1]
if out:
    cnt = {}
    for r in rows:
        cnt[r[3]] = cnt.get(r[3], 0) + 1
    with open(os.path.join(ROOT, out), 'w') as fp:
        fp.write('# Real Racing HD -- import table\n\n')
        fp.write('Generated by `python3 -I tools/imports_check.py --md docs/imports.md` from '
                 '`decompiled/macho/imports.txt` (365 symbols, cross-checked with `otool -Iv`).\n\n')
        fp.write('Status: **real** = implemented / bound to the VitaSDK library; **stub** = logged no-op or '
                 '"unavailable" result; **dynamic** = created at bind time by `objc_import_lookup`; '
                 '**MISSING** = would land in `ml_unimpl_entry` (`[UNIMPL]` in the log).\n\n')
        fp.write('Totals: ' + ', '.join('%s %d' % (k, v) for k, v in sorted(cnt.items())) + '\n\n')
        for a in sorted(set(r[0] for r in rows)):
            fp.write('## %s\n\n| Symbol | Shim | Status |\n|---|---|---|\n' % a)
            for r in sorted(x for x in rows if x[0] == a):
                fp.write('| `%s` | `%s` | %s |\n' % (r[1], r[2], r[3]))
            fp.write('\n')
cnt = {}
for r in rows:
    cnt[r[3]] = cnt.get(r[3], 0) + 1
print('imports: %d  %s' % (len(rows), ' '.join('%s=%d' % kv for kv in sorted(cnt.items()))))
for s in missing:
    print('MISSING', s, '(%s)' % area(s))
sys.exit(1 if missing else 0)
